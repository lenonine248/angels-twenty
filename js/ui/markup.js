// 画面に出す短い文の記法。仕様書 §79.6。
//
// ブリーフィング・チュートリアル・更新履歴の文は、いずれもソースの中に
// **強調** や改行を書いた素の文字列として置いてある。それを HTML に変える。
//
// **書いてある記法と、出る見た目を1か所で決める。**
// もともと変換していたのは更新履歴だけで、ブリーフィングとチュートリアルは
// 素のまま `innerHTML` に流していた。書いた側は太字のつもりで、
// 画面には `**射程に入っても**` と星印がそのまま出ていた ——
// **チュートリアルの補足だけで122か所**（実測）。
//
// ステージの説明文にも同じ記法で書かれた箇所は今のところ無いが、
// 通り道は揃えてある。片方だけ素通しにしておくと、次に誰かが
// 太字のつもりで書いたときに、また星印のまま出る。
//
// 対応するのは、実際に使っている記法だけ:
//
//   **強調**            → <b>
//   `コード`            → <code>
//   [文字](リンク)      → 文字だけ残す
//   改行                → <br>（block のみ）
//
// **必ず先にエスケープする。** ここを通る文は作者が書いたものだけだが、
// ステージエディタで作った文（プレイヤーが打つ）も同じ道を通るため。

/** HTML として意味を持つ文字を潰す */
export function escapeHtml(s) {
  return String(s).replace(/[&<>"]/g, (c) => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}

/** 1行ぶんの記法。改行は変換しない（見出しや項目に使う） */
export function inline(s) {
  return escapeHtml(s == null ? '' : s)
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')     // リンクは文字だけ残す
    .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')
    .replace(/`([^`]+)`/g, '<code>$1</code>');
}

/** 段落ぶんの記法。改行を `<br>` にする */
export function block(s) {
  return inline(s).replace(/\n/g, '<br>');
}
