// 開発サーバの上にいるか。仕様書 §23.8。
//
// **受け口の有無で分ける。** `devserver.py` はリプレイの保存・一覧・プレイ記録の
// 受け口を持つが、**公開版（GitHub Pages）は静的な配信だけ**で何も持たない。
//
// 無いところへ問い合わせると、`try/catch` で握り潰しても
// **ブラウザのコンソールには 404 が赤字で残る**（実際に残った）。
// 掴めないものは**そもそも叩かない。**
//
// `devserver.py` は `127.0.0.1` にしか口を開けないので、
// 判定はホスト名だけで足りる。

/** 開発サーバの受け口が期待できるか */
export function onDevServer() {
  const h = location.hostname;
  return h === 'localhost' || h === '127.0.0.1' || h === '[::1]';
}
